    @Test
    fun `el cliente HTTP serializa y deserializa correctamente las rutas del contrato OpenAPI`() = runTest {
        val capturedAuthHeaders = mutableMapOf<String, String?>()
        val mockEngine = MockEngine { request ->
            capturedAuthHeaders[request.url.encodedPath] = request.headers[HttpHeaders.Authorization]
            val jsonHeaders = headersOf(HttpHeaders.ContentType, ContentType.Application.Json.toString())
            when (request.url.encodedPath) {
                "/healthz" -> respond(
                    content = """{"status":"ok","product":"RosaFiesta"}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/payments/summary" -> respond(
                    content = """{"summary":{"monthLabel":"Octubre 2026","octRevenueRD":12450,"accountsReceivableRD":7724,"activeEventsCount":4,"newQuoteRequests":2,"pendingVerificationCount":1}}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/quotes/rosa-proposal" -> respond(
                    content = """{"proposal":{"step":7,"eventType":"Boda","styleTitle":"Rosa & Dorado","colorPalette":["#EA4EA9","#FFD45C"],"guests":120,"budgetRD":4500,"suggestedLines":[{"articleCode":"RF-001","name":"Silla Tiffany dorada","quantity":120,"unitPriceRD":4}],"estimatedTotalRD":4500,"depositRequiredRD":1350,"assistantReply":"Propuesta lista"}}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/catalog/balloons" -> respond(
                    content = """{"articles":[{"id":"balloon-bouquet-helio","name":"Bouquet helio","categoryId":"globos","photoKey":"arco_rosa","dailyPriceDop":28,"totalStock":85,"availableStock":64,"lowStockThreshold":10,"description":"Bouquet de 7 globos","isDirectSale":true,"visible":true}]}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/refunds" -> respond(
                    content = """{"refunds":[{"id":"ref-rafael-soto","eventId":"evt-aniversario-soto","eventTitle":"Aniversario Soto","clientName":"Rafael Soto","paidRD":1800,"refundPercent":90,"refundRD":1620,"reason":"Reprogramacion","status":"PENDING"}]}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/reports/export" -> respond(
                    content = """{"report":{"reportType":"ingresos","period":"2026-10","filename":"ingresos-2026-10.csv","currency":"DOP","totalRD":12450,"itbisRD":2241,"generatedAt":"20 oct 2026","csv":"id,monto\n1,12450","series":[{"label":"Semana 1","valueRD":12450,"count":5}]}}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/auth/oauth/google/start" -> respond(
                    content = """{"provider":"google","authorizeUrl":"https://accounts.google.com/o/oauth2/v2/auth?state=state-1","state":"state-1"}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/auth/oauth/exchange" -> respond(
                    content = """{"accessToken":"oauth-jwt-token","expiresIn":86400,"user":{"id":"usr-1","fullName":"Yulissa Marte","email":"yuli@rosafiesta.do","role":"CLIENT","activeView":"personal","phone":"+1 809-555-0142"}}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )

                "/v1/devices/push-token" -> if (request.method == HttpMethod.Delete) {
                    respond(
                        content = """{"disabled":true}""",
                        status = HttpStatusCode.OK,
                        headers = jsonHeaders,
                    )
                } else {
                    respond(
                        content = """{"registered":true,"device":{"id":"dev-1","userId":"usr-1","platform":"android","token":"fcm-token-123","appVariant":"personal","enabled":true,"updatedAt":"2026-11-15T16:00:00Z"}}""",
                        status = HttpStatusCode.OK,
                        headers = jsonHeaders,
                    )
                }

                else -> respond(
                    content = """{"articles":[{"id":"silla-tiffany","name":"Silla Tiffany dorada","categoryId":"mobiliario","photoKey":"silla-tiffany","dailyPriceDop":4,"totalStock":240,"availableStock":120,"lowStockThreshold":20,"description":"Silla dorada","visible":true}]}""",
                    status = HttpStatusCode.OK,
                    headers = jsonHeaders,
                )
            }
        }

        val httpClient = HttpClient(mockEngine) {
            install(ContentNegotiation) {
                json(Json { ignoreUnknownKeys = true })
            }
        }
        var dynamicToken: String? = "provider-jwt-token"
        val api = RosaFiestaApiClient(
            baseUrl = "http://localhost:8788",
            httpClient = httpClient,
            accessTokenProvider = { dynamicToken },
        )

        val health = api.fetchHealth()
        assertEquals("ok", health.status)
        assertEquals("RosaFiesta", health.product)

        val summary = api.getFinanceSummary()
        assertEquals(12450L, summary.summary.octRevenueRD)
        assertEquals(7724L, summary.summary.accountsReceivableRD)
        assertEquals("Bearer provider-jwt-token", capturedAuthHeaders["/v1/payments/summary"])

        api.setAccessToken("explicit-session-token")
        val refunds = api.listRefunds()
        assertEquals("Rafael Soto", refunds.refunds!!.first().clientName)
        assertEquals("Bearer explicit-session-token", capturedAuthHeaders["/v1/refunds"])

        val report = api.exportReport(type = "ingresos", period = "2026-10")
        assertEquals(12450L, report.report.totalRD)
        assertEquals("Bearer explicit-session-token", capturedAuthHeaders["/v1/reports/export"])

        api.setAccessToken(null)
        dynamicToken = null

        val proposal = api.generateRosaProposal(RosaProposalInputDto(eventType = "Boda", guests = 120, budgetRD = 4500))
        assertEquals(4500L, proposal.proposal.estimatedTotalRD)
        assertEquals(1350L, proposal.proposal.depositRequiredRD)

        val balloons = api.listBalloonProducts()
        assertEquals("balloon-bouquet-helio", balloons.articles!!.first().id)
        assertEquals(28L, balloons.articles.first().dailyPriceDop)

        val articles = api.listArticles("silla")
        assertTrue(articles.articles!!.isNotEmpty())
        assertEquals(4L, articles.articles.first().dailyPriceDop)

        val oauthStart = api.startOAuthAuthorization(
            provider = "google",
            redirectUri = "http://127.0.0.1:43123/callback",
            codeChallenge = "challenge-abc",
            state = "state-1",
        )
        assertEquals("google", oauthStart.provider)
        assertEquals("state-1", oauthStart.state)

        val oauthSession = api.exchangeOAuthCode(
            OAuthExchangeInputDto(
                provider = "google",
                code = "auth-code-123",
                codeVerifier = "verifier-xyz",
                redirectUri = "http://127.0.0.1:43123/callback",
            ),
        )
        assertEquals("oauth-jwt-token", oauthSession.accessToken)
        assertEquals("yuli@rosafiesta.do", oauthSession.user.email)

        api.setAccessToken("explicit-session-token")
        val pushRegistered = api.registerDevicePushToken(
            PushTokenInputDto(
                platform = "android",
                token = "fcm-token-123",
                appVariant = "personal",
            ),
        )
        assertTrue(pushRegistered.registered)
        assertEquals("fcm-token-123", pushRegistered.device.token)
        assertEquals("Bearer explicit-session-token", capturedAuthHeaders["/v1/devices/push-token"])

        val pushDisabled = api.unregisterDevicePushToken("fcm-token-123")
        assertTrue(pushDisabled.disabled)
    }
